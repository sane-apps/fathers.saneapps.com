#!/usr/bin/env python3
"""Generate the Cloudflare Pages Function that blocks withdrawn /works/* URLs.

Cloudflare Pages can keep serving a per-hostname "preservation" copy when the
current deployment has no asset for a path. Zone purges do not clear it, which
is why fathers.saneapps.com returned 200 for held works while the deployment
URL returned 404. This Function runs before the asset server for /works/* and
returns a real 404 unless the slug is in the current live allowlist.

/authors/* gets the same gate: an author whose only work was withheld kept a
200 page on the custom domain that linked to a 404 work (2026-10-07: Macarius,
Pseudo-Cyprian).
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SLUG_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
SECTION_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9.\-]*$")

FUNCTION_TEMPLATE = """\
/** Generated by scripts/generate_works_gate.py — do not edit by hand. */
const LIVE = new Set({live_json});
// _redirects never reaches these paths: this Function answers first, so
// /authors/irenaeus-of-lyons/ was a 404 (2026-10-14). Moved slugs live here.
const MOVED = {moved_json};

const NOT_FOUND_HTML = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex">
<title>Page unavailable</title>
</head>
<body>
<section>
<h1>Page unavailable</h1>
<p>This page is not in the current library.</p>
<p><a href="/works/">Browse works</a> or <a href="/topics/">browse topics</a>.</p>
</section>
</body>
</html>
`;

function pathSegments(params) {{
  const raw = params.path;
  if (raw == null || raw === "") return [];
  return Array.isArray(raw) ? raw : [raw];
}}

const NOT_FOUND_HEADERS = {{
  "content-type": "text/html; charset=utf-8",
  "cache-control": "private, no-store",
  "x-robots-tag": "noindex",
}};

// The site's own styled 404 page (nav, fonts, search), with status 404. The
// bare page above is only the fallback if that asset cannot be read
// (2026-10-14 audit: held and renamed works landed on an unstyled page).
async function notFound(context) {{
  try {{
    const res = await context.env.ASSETS.fetch(new Request(new URL("/404", context.request.url), {{ method: "GET" }}));
    if (res.status === 200) {{
      return new Response(await res.text(), {{ status: 404, headers: NOT_FOUND_HEADERS }});
    }}
  }} catch (err) {{
    // fall through to the bare page
  }}
  return new Response(NOT_FOUND_HTML, {{ status: 404, headers: NOT_FOUND_HEADERS }});
}}

export async function onRequest(context) {{
  const segments = pathSegments(context.params);
  if (segments.length === 0) {{
    return context.env.ASSETS.fetch(context.request);
  }}
  const slug = segments[0];
  // A moved page inside a live work (a cite page whose section id changed).
  const page = segments.filter(Boolean).join("/");
  if (page !== slug && Object.prototype.hasOwnProperty.call(MOVED, page)) {{
    return Response.redirect(new URL(MOVED[page], context.request.url).toString(), 301);
  }}
  if (LIVE.has(slug)) {{
    return context.env.ASSETS.fetch(context.request);
  }}
  if (Object.prototype.hasOwnProperty.call(MOVED, slug)) {{
    return Response.redirect(new URL(MOVED[slug], context.request.url).toString(), 301);
  }}
  return notFound(context);
}}
"""

ROUTES_JSON = {
    "version": 1,
    "include": ["/works/*", "/authors/*", "/api/*", "/dl/*"],  # /api: search + library pass; /dl: paid downloads (functions/dl)
    "exclude": [],
}


def live_slugs_from_works_dir(works_dir: Path) -> list[str]:
    if not works_dir.is_dir():
        raise SystemExit(f"BLOCKED: works dir missing: {works_dir}")
    slugs = sorted(
        p.name
        for p in works_dir.iterdir()
        if p.is_dir() and (p / "index.html").is_file() and SLUG_RE.fullmatch(p.name)
    )
    if not slugs:
        raise SystemExit(f"BLOCKED: no live work slugs under {works_dir}")
    return slugs


def moved_slugs(redirects: Path, section: str, live: list[str]) -> dict[str, str]:
    """`/section/<old>/ /target/ 301` lines of _redirects whose old slug is not
    live, plus `/section/<slug>/<page>/` lines (a moved cite page: the Function
    answers /works/* first, so _redirects never sees them). Placeholders and
    splats stay with _redirects. Status lines that are not redirects (ship.sh
    adds `/works/<held>/ /404.html 404`) stay 404s."""
    moved: dict[str, str] = {}
    try:
        lines = redirects.read_text(encoding="utf-8").splitlines()
    except OSError:
        return moved
    prefix, live_set = f"/{section}/", set(live)
    for line in lines:
        parts = line.split()
        if len(parts) < 2 or not parts[0].startswith(prefix) or ":" in parts[0] or "*" in parts[0]:
            continue
        if len(parts) > 2 and not parts[2].startswith("3"):
            continue
        rest = parts[0][len(prefix):].strip("/")
        if rest and "/" not in rest and SLUG_RE.fullmatch(rest) and rest not in live_set:
            moved[rest] = parts[1]
        elif rest.count("/") == 1:
            slug, page = rest.split("/")
            if SLUG_RE.fullmatch(slug) and SECTION_RE.fullmatch(page):
                moved[rest] = parts[1]
    return moved


def write_gate(functions_dir: Path, slugs: list[str], section: str = "works",
               moved: dict[str, str] | None = None) -> Path:
    target = functions_dir / section / "[[path]].js"
    target.parent.mkdir(parents=True, exist_ok=True)
    live_json = json.dumps(slugs, separators=(",", ":"))
    moved_json = json.dumps(moved or {}, separators=(",", ":"), sort_keys=True)
    target.write_text(FUNCTION_TEMPLATE.format(live_json=live_json, moved_json=moved_json), encoding="utf-8")
    return target


def write_routes(stage_dir: Path) -> Path:
    path = stage_dir / "_routes.json"
    path.write_text(json.dumps(ROUTES_JSON, indent=2) + "\n", encoding="utf-8")
    return path


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--works-dir",
        type=Path,
        default=None,
        help="Directory of live /works/<slug>/ folders (default: <stage>/works or dist/works)",
    )
    parser.add_argument(
        "--stage",
        type=Path,
        default=None,
        help="Pages upload directory; writes _routes.json here when set",
    )
    parser.add_argument(
        "--functions-dir",
        type=Path,
        default=ROOT / "functions",
        help="Pages Functions directory (default: repo functions/)",
    )
    parser.add_argument(
        "--print-slugs",
        action="store_true",
        help="Include slug list in the receipt JSON",
    )
    args = parser.parse_args()

    works_dir = args.works_dir
    if works_dir is None:
        if args.stage is not None:
            works_dir = args.stage / "works"
        else:
            works_dir = ROOT / "dist" / "works"

    slugs = live_slugs_from_works_dir(works_dir)
    redirects = works_dir.parent / "_redirects"
    gate_path = write_gate(args.functions_dir, slugs, "works", moved_slugs(redirects, "works", slugs))
    authors = live_slugs_from_works_dir(works_dir.parent / "authors")
    authors_path = write_gate(args.functions_dir, authors, "authors", moved_slugs(redirects, "authors", authors))
    routes = write_routes(args.stage) if args.stage is not None else None
    receipt = {
        "live_works": len(slugs),
        "live_authors": len(authors),
        "function": str(gate_path),
        "authors_function": str(authors_path),
        "routes": str(routes) if routes else None,
    }
    if args.print_slugs:
        receipt["slugs"] = slugs
    print(json.dumps(receipt, indent=2))


if __name__ == "__main__":
    main()
